"""Generate docs/research2/RESULTS_V2.md from the analysis files (numbers are never typed by hand).

Usage: python src/scripts/make_r2_v2_results.py   (rerun after the latency benchmark to fill §5)
"""
# ruff: noqa: E501, E741, B007
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
V9 = ROOT / "artifacts/research2/v2/v9"
RUNS = ROOT / "artifacts/research2/v2/runs"
test = json.loads((V9 / "analysis_test.json").read_text())
val = json.loads((V9 / "analysis_val.json").read_text())
flops = json.loads((V9 / "inference_flops.json").read_text())
partner = json.loads((V9 / "case4_partner.json").read_text())
policies = json.loads((V9 / "roi_policies.json").read_text())
lat_path = V9 / "latency_val.json"
lat = json.loads(lat_path.read_text()) if lat_path.exists() else None
DELTA = 0.007
NAMES = {"siam_unet_resnet18": "Siamese U-Net + ResNet-18", "scannet": "SCanNet + ResNet-34",
         "mamba_scd": "MambaSCD-Tiny"}
SHORT = {"siam_unet_resnet18": "unet", "scannet": "scannet", "mamba_scd": "mamba"}
P = "frontier0.5"
CASES = ("case2", "case3", "case4")
CASE_NAME = {"case2": "2 (Medium, LEVIR-CD init)", "case3": "3 (Medium, SECOND only)",
             "case4": "4 (Medium ∨ Light Resized)"}


def ci(a):
    return f"{a[0]:+.4f}…{a[1]:+.4f}"


def verdict(model, case):
    e = test["models"][model]
    s = e["systems"][f"{case}__{P}"]
    c = e["comparisons"][f"{case}__{P}_vs_single"]
    non_inferior = c["ci95"][0] > -DELTA
    cheaper = s["flops_ratio_ci95"][1] < 1
    better = c["ci95"][0] > 0
    worse = c["ci95"][1] < 0
    dearer = s["flops_ratio_ci95"][0] > 1
    if non_inferior and cheaper:
        return "two-stage preferable"
    if (cheaper and not non_inferior) or (better and dearer):
        return "trade-off"
    if worse and dearer:
        return "single-stage preferable"
    if non_inferior and dearer:
        return "single-stage preferable (not cheaper, no gain)"
    return "inconclusive"


L = []
w = L.append
w("# Research 2 v2 — results (frozen protocol v0.4)\n")
w("Generated by a script from `artifacts/research2/v2/v9/analysis_test.json` (test) and `analysis_val.json` (validation); "
  "no number in this file is typed by hand. Test split read once (claim `freeze_manifest_v2.json.test_read.json`).\n")
w("## 1. Question and answer\n")
w("*Under which accuracy and compute-budget conditions is a two-stage semantic change detection system preferable to a "
  "single-stage model on SECOND?*  \n")
w("**Short answer (SECOND, our implementation, primary ROI policy `frontier0.5`, FLOPs as compute):** in none of the nine "
  "model × detector settings is the two-stage system *preferable* by the pre-declared rule. Accuracy is non-inferior "
  f"(margin δ = {DELTA}) for all three SCD models, but the two-stage system costs **more** inference FLOPs than the single-stage "
  "model, because the detector alone costs about as much as a Siamese U-Net pass and the context windows add the area back. "
  "Only the aggressive `frontier0.3` policy gets below the single-stage FLOPs (SCanNet only), at a clearly inferior SeK. "
  "A negative result is a valid outcome (D-001). Wall-clock latency points the same way (§5).\n")
adj_all = test["primary_holm"]["adjusted_p"]
sig = [k for k, v in adj_all.items() if v < 0.05]
w("Findings in one list (all from the tables below):")
w("- **H2 (central).** Non-inferiority holds for every SCD model (all Holm p < 0.001): ΔSeK = " + ", ".join(
    f"{NAMES[m]} {test['models'][m]['comparisons'][f'case2__{P}_vs_single']['diff_sek']:+.4f}" for m in NAMES) +
  f" vs δ = {DELTA}. Compute: FLOPs ratio " + ", ".join(
    f"{NAMES[m]} ×{test['models'][m]['systems'][f'case2__{P}']['flops_ratio_vs_single']:.2f}" for m in NAMES) +
  " — the two-stage system is not cheaper in FLOPs for any model. Verdicts: " + ", ".join(
    f"{NAMES[m]}: {verdict(m, 'case2')}" for m in NAMES) + ".")
w("- **Why.** At `frontier0.5` the boxes cover about half of the tile, but the context windows bring the processed area back to "
  "≈ 1.0× the tile, and the detector adds one more Medium forward pass (130 GFLOPs). Oracle ROIs (ground-truth boxes) would process 0.70 of the area at ≈ 0.98× FLOPs (no detector charged).")
w("- **H3 (detector training).** case 2 vs case 3: " + ("no significant difference after Holm" if not any("case2 vs case3" in k for k in sig)
  else "significant for some models") + " (Holm p = " + ", ".join(
    f"{v:.2f}" for k, v in adj_all.items() if "case2 vs case3" in k) + "); the LEVIR-CD initialisation gives at most +0.001 SeK.")
w("- **H4 (OR ensemble).** case 4 vs case 2: " + ("no significant difference after Holm" if not any("case4 vs case2" in k for k in sig)
  else "significant for some models") + " (Holm p = " + ", ".join(
    f"{v:.2f}" for k, v in adj_all.items() if "case4 vs case2" in k) + "); the extra detector costs FLOPs without a reliable gain.")
if lat is not None:
    w("- **Latency (wall-clock, validation tiles, batch 1).** Median ratio vs single-stage at `" + P + "` (case 2): " + ", ".join(
        f"{NAMES[m]} ×{lat[m][f'case2__{P}']['ratio_vs_single']['median']:.2f} "
        f"(CI {lat[m][f'case2__{P}']['ratio_vs_single']['ci95'][0]:.2f}…{lat[m][f'case2__{P}']['ratio_vs_single']['ci95'][1]:.2f})"
        for m in NAMES) + " — slower for every model, also at `frontier0.3`; wall-clock does not rescue the two-stage system "
        "(box generation, host round trips and several small batches per tile cost more than the saved area).")
w("- **H5 (density).** The penalty of SCanNet and MambaSCD is larger on tiles with little change (−0.006…−0.010) than on dense tiles (−0.002…−0.005); "
  "for U-Net the two-stage system gains on sparse tiles (+0.003) and loses slightly on dense ones.")
w("- **H1 (architecture).** Single-stage SeK: " + ", ".join(
    f"{NAMES[m]} {test['models'][m]['systems']['single']['sek']['mean']:.4f}" for m in NAMES) + " (SCanNet ≳ MambaSCD ≫ U-Net at equal training FLOPs).\n")
w("## 2. What was frozen\n")
w("- 12 systems = 3 SCD models (trained by us on SECOND, equal training FLOPs b* = 3.2e17, HPO 6 × 8e16 per model, 3 seeds) × "
  "case 1 (single-stage) and cases 2–4 (two-stage, detector → ROI → same SCD checkpoint on context windows, `batch_ctx`).")
w(f"- δ = **{DELTA}**; density edges {test['density_edges'][0]:.4f} / {test['density_edges'][1]:.4f}; primary policy `{P}`; "
  f"case-4 partner = `{partner['partner']}` (seed-mean ΔF1 vs Medium alone: " +
  ", ".join(f"{k} {v['mean_delta_f1']:+.4f}" for k, v in partner["candidates"].items()) + ").")
w("- ROI policies (selected on validation): " +
  "; ".join(f"{c}: " + ", ".join(f"{k}={v['threshold']:g}/{v['margin']}/{v['merge_gap']}/{v['min_crop']}"
                                for k, v in policies[c].items()) for c in CASES) + " (threshold/margin/gap/min side).\n")
w("## 3. Training (validation)\n")
w("| model | HPO winner (lr, wd) | val SeK seeds 42/123/777 (best epoch) | mean ± SD |")
w("|---|---|---|---|")
for m in NAMES:
    sel = json.loads((RUNS / "hpo" / m / "search_result.json").read_text())["selected"]
    rows = []
    for s in (42, 123, 777):
        r = json.loads((RUNS / "final" / m / f"{SHORT[m]}_final_s{s}" / "run_record.json").read_text())
        rows.append((r["best_sek"], r["best_epoch"]))
    import statistics as st
    w(f"| {NAMES[m]} | {sel['lr']}, {sel['weight_decay']} | " + " / ".join(f"{a:.4f} ({b})" for a, b in rows) +
      f" | {st.mean(a for a, _ in rows):.4f} ± {st.stdev(a for a, _ in rows):.4f} |")
w("\nDetectors (val pixel F1 at the best threshold, seeds 42/123/777), B = 3e16 FLOPs: ")
for name, group, det in (("Medium fine-tuned (screening finals)", "screening", "medium_full"),
                         ("Medium scratch", "v9_medium_scratch", "medium_full"),
                         ("Light Resized fine-tuned", "v9_light_resized", "light_resized")):
    vals = []
    for s in (42, 123, 777):
        tmpl = f"{det}_s{s}" if group == "screening" else (f"medium_scratch_s{s}" if "medium" in group else f"light_resized_s{s}")
        p = RUNS / group / det / tmpl / "run_record.json"
        if p.exists():
            vals.append(json.loads(p.read_text()).get("best_validation_f1"))
    if vals:
        w(f"- {name}: " + " / ".join(f"{v:.4f}" for v in vals if v))
w("\nCaveats: MambaSCD and U-Net trained far past their plateau (best epoch 39–54 of 120 and ≈ 60 of 360; best-epoch selection on val); "
  "SCanNet's HPO horizon (12 epochs) is below its plateau; five of the nine SCD runs were interrupted by a server restart and resumed exactly from "
  "`last.pt` (≤ 1 epoch lost; MambaSCD is not bitwise reproducible anyway).\n")
w("## 4. Test results\n")
w(f"1694 SECOND test tiles, three seeds, paired scene bootstrap nested with seeds (2000 resamples). δ = {DELTA}.\n")
w("### 4.1 H1 — the three single-stage models (equal training FLOPs)\n")
w("| model | test SeK (mean ± SD) | mIoU | Fscd | forward GFLOPs / 512² tile |")
w("|---|---|---|---|---|")
for m in NAMES:
    s = test["models"][m]["systems"]["single"]
    w(f"| {NAMES[m]} | {s['sek']['mean']:.4f} ± {s['sek']['sd']:.4f} | {s['miou']['mean']:.4f} | {s['fscd']['mean']:.4f} | "
      f"{flops['scd'][m]['512'] / 1e9:.0f} |")
w("\n### 4.2 Two-stage vs single-stage, primary policy `frontier0.5` (P1–P3 and descriptive)\n")
w("| SCD model | case | SeK | ΔSeK vs single (CI95) | non-inferior (δ) | FLOPs / single (CI95) | box area | window area | crops | verdict |")
w("|---|---|---|---|---|---|---|---|---|---|")
for m in NAMES:
    e = test["models"][m]
    for c in CASES:
        s = e["systems"][f"{c}__{P}"]
        cmp_ = e["comparisons"][f"{c}__{P}_vs_single"]
        ni = "yes" if cmp_["ci95"][0] > -DELTA else "no"
        w(f"| {NAMES[m]} | {CASE_NAME[c]} | {s['sek']['mean']:.4f} | {cmp_['diff_sek']:+.4f} ({ci(cmp_['ci95'])}) | {ni} | "
          f"{s['flops_ratio_vs_single']:.2f} ({s['flops_ratio_ci95'][0]:.2f}…{s['flops_ratio_ci95'][1]:.2f}) | "
          f"{s['box_area_ratio']:.2f} | {s['window_area_ratio']:.2f} | {s['crops_per_tile']:.1f} | {verdict(m, c)} |")
w("\n*Box area* = fraction of the tile inside the ROI boxes; *window area* = fraction actually processed by the SCD model after the 128/256/384/512 "
  "context windows are cut (the difference is why FLOPs do not follow the box area).\n")
w("### 4.3 Accuracy–compute curve (all ROI policies, case 2; ΔSeK vs single, FLOPs ratio)\n")
w("| SCD model | balanced | frontier0.7 | frontier0.5 | frontier0.3 |")
w("|---|---|---|---|---|")
for m in NAMES:
    e = test["models"][m]
    cells = []
    for pol in ("balanced", "frontier0.7", "frontier0.5", "frontier0.3"):
        c = e["comparisons"][f"case2__{pol}_vs_single"]
        cells.append(f"{c['diff_sek']:+.4f} / ×{e['systems'][f'case2__{pol}']['flops_ratio_vs_single']:.2f}")
    w(f"| {NAMES[m]} | " + " | ".join(cells) + " |")
w("\n### 4.4 Pre-declared primary comparisons P1–P9 (Holm-adjusted over the family of nine)\n")
w("| id | comparison | ΔSeK (CI95) | raw p | Holm p |")
w("|---|---|---|---|---|")
raw = test["primary_holm"]["raw_p"]
adj = test["primary_holm"]["adjusted_p"]
n = 0
for kind, key, a in (("P1–P3", "case2 vs single", "case2__{P}_vs_single"),
                     ("P4–P6", "case2 vs case3", "case2_vs_case3__{P}"),
                     ("P7–P9", "case4 vs case2", "case4_vs_case2__{P}")):
    for m in NAMES:
        n += 1
        c = test["models"][m]["comparisons"][a.format(P=P)]
        k = f"{kind.replace(chr(8211), chr(45)).replace('P1-P3','P1-3').replace('P4-P6','P4-6').replace('P7-P9','P7-9')} {m} {key}"
        w(f"| P{n} | {NAMES[m]}: {key} | {c['diff_sek']:+.4f} ({ci(c['ci95'])}) | {raw[k]:.4f} | {adj[k]:.4f} |")
w("\nP1–P3 are one-sided non-inferiority tests against −δ; P4–P9 one-sided superiority tests. A Holm-adjusted p < 0.05 is required for a claim. "
  "Compute (FLOPs and latency) is judged separately by the decision rule (§4.2 verdict).\n")
w("### 4.5 H5 — changed-pixel density strata (case − single, primary policy; terciles frozen on validation)\n")
w("| SCD model | stratum (ρ range, tiles) | case 2 − single | case 3 − single | case 4 − single |")
w("|---|---|---|---|---|")
e0, e1 = test["density_edges"]
ranges = [f"ρ < {e0:.3f}", f"{e0:.3f} ≤ ρ < {e1:.3f}", f"ρ ≥ {e1:.3f}"]
for m in NAMES:
    for k, x in test["models"][m]["strata"].items():
        w(f"| {NAMES[m]} | {ranges[int(k)]} ({x['tiles']}) | " + " | ".join(
            f"{x[f'{c}_minus_single']['diff']:+.4f} ({ci(x[f'{c}_minus_single']['ci95'])})" for c in CASES) + " |")
w("\n### 4.6 Diagnostic — oracle ROIs (boxes from the ground-truth mask, not a system)\n")
w("| SCD model | single SeK | oracle-ROI SeK | gain | oracle FLOPs / single |")
w("|---|---|---|---|---|")
for m in NAMES:
    e = test["models"][m]["systems"]
    w(f"| {NAMES[m]} | {e['single']['sek']['mean']:.4f} | {e['oracle__balanced']['sek']['mean']:.4f} | "
      f"{e['oracle__balanced']['sek']['mean'] - e['single']['sek']['mean']:+.4f} | {e['oracle__balanced']['flops_ratio_vs_single']:.2f} |")
w("\nA perfect ROI would add 0.017–0.021 SeK, i.e. there is headroom, but real detectors (pixel recall 0.86–0.89 at the primary policy) do not "
  "capture it: every missed changed pixel is lost.\n")
w("## 5. Latency (validation tiles, batch 1, fp32, TF32 off)\n")
if lat is None:
    w("*Pending: the benchmark waits for a quiet GPU (all cards carry foreign load); see `latency_watch.log`.*\n")
else:
    meta = lat["_meta"]
    w(f"GPU {meta['gpu']}, {meta['tiles'] - meta['warmup_tiles']} timed tiles, seed {meta['seed']}; background before "
      f"{meta['background_before']}, after {meta['background_after']}. The card was quiet when the run started; foreign load appeared "
      "during the run (mean utilisation afterwards above), so absolute milliseconds, mainly of the later SCanNet and MambaSCD parts, may be inflated. "
      "Systems are interleaved per tile and ratios are paired per tile, which makes the ratios robust to such load; they were not re-measured on a fully idle card.\n")
    w("| SCD model | system | median ms | p95 ms | detector stage ms | ratio vs single (median of per-tile ratios, CI95) |")
    w("|---|---|---|---|---|---|")
    for m in NAMES:
        for key in ("single", f"case2__{P}", f"case3__{P}", f"case4__{P}", "case2__frontier0.3"):
            x = lat[m][key]
            r = x["ratio_vs_single"]
            w(f"| {NAMES[m]} | {key} | {x['median_ms']:.1f} | {x['p95_ms']:.1f} | {x['detector_stage_median_ms']:.1f} | "
              f"{r['median']:.2f} ({r['ci95'][0]:.2f}…{r['ci95'][1]:.2f}) |")
w("\n## 6. Limitations\n")
for t in [
    "Single dataset (SECOND), one implementation of each architecture, three seeds; spatial dependence between tiles is not modelled (no geographic metadata).",
    "ROI policies, the case-4 partner and δ were chosen on the same validation tiles used to select detectors and checkpoints (optimistic for two-stage); the test set was read once.",
    "SCD models see only context windows at test time (D-050, no retraining on crops): a deliberately unfavourable condition for two-stage, probed by ablation B (H6) which is **not run** in this protocol version.",
    "FLOPs follow `FlopCounterMode` + analytic selective scan; detector training compute is reported but not charged to the SCD budget (D-050).",
    "Latency was measured on validation tiles on a shared server; see §5 for the recorded background load.",
    "Reimplementation fidelity of SCanNet and MambaSCD against the published code was checked only on the reference checkpoints (V4-T05); absolute SeK is far below published numbers because our training budget and recipe are far smaller.",
]:
    w(f"- {t}")
results_path = ROOT / "docs/research2/RESULTS_V2.md"
results_path.parent.mkdir(parents=True, exist_ok=True)
results_path.write_text("\n".join(L) + "\n")
print("written", len(L), "lines")
